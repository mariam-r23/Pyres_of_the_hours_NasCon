"""Regenerate dialogue/tests/picker_cases.json from the Python picker.

The Python picker is checked by tests/test_dialogue.py (hand-written expectations).
This file only records its outputs so that dialogue/dialogue_picker.gd can be checked against them
by dialogue/tests/run_picker_tests.gd. Do not hand-edit the generated file.
    python gen_dialogue_cases.py
"""
import json
import os
import sys

sys.path.insert(0, os.path.dirname(__file__))
from pyre_ref.dialogue import DialoguePicker, Rng, seed_from_string  # noqa: E402

OUT = os.path.join(os.path.dirname(__file__), "..", "..", "dialogue", "tests", "picker_cases.json")

CONFIG = {
    "recent_window": 3,
    "allowed_moods": {
        "1": ["amused", "annoyed", "triumphant"],
        "2": ["amused", "annoyed", "menacing"],
        "3": ["menacing", "triumphant"],
    },
}

LINES = [
    {"id": "a1_t_amu", "act": 1, "trigger": "t", "mood": "amused", "text": "one amused"},
    {"id": "a1_t_ann", "act": 1, "trigger": "t", "mood": "annoyed", "text": "one annoyed"},
    {"id": "a1_t_tri", "act": 1, "trigger": "t", "mood": "triumphant", "text": "one triumphant"},
    {"id": "a2_t_men", "act": 2, "trigger": "t", "mood": "menacing", "text": "two menacing"},
    {"id": "a3_t_men", "act": 3, "trigger": "t", "mood": "menacing", "text": "three menacing"},
    {"id": "a1_u_amu", "act": 1, "trigger": "u", "mood": "amused", "text": "u amused"},
    {"id": "a1_u_ann", "act": 1, "trigger": "u", "mood": "annoyed", "text": "u annoyed"},
    {"id": "a1_solo", "act": 1, "trigger": "solo", "mood": "amused", "text": "only line"},
]

W1 = {"amused": 0.6, "annoyed": 0.2, "triumphant": 0.2}


def ctx(act, mood, weights=None):
    c = {"act": act, "spirit_mood": mood}
    if weights is not None:
        c["mood_weights"] = weights
    return c


SCENARIOS = [
    ("act 1 weighted mix over 12 calls", "L01_first_crate", CONFIG,
     [("t", ctx(1, "amused", W1))] * 12),
    ("act 1 never gets later-act lines", "L02_wake_the_shadow", CONFIG,
     [("t", ctx(1, "amused", {"amused": 1, "annoyed": 1, "triumphant": 1}))] * 15),
    ("act 2 menacing only", "L05_x", CONFIG, [("t", ctx(2, "menacing"))] * 6),
    ("act 3 prefers act 3 lines", "L09_x", CONFIG, [("t", ctx(3, "menacing"))] * 6),
    ("disallowed mood falls back to the act's first allowed mood", "L09_y", CONFIG,
     [("t", ctx(3, "amused", {"amused": 1.0}))] * 3),
    ("zero weights fall back to the act's first allowed mood", "L02_z", CONFIG,
     [("t", ctx(1, "amused", {"amused": 0.0, "annoyed": 0.0}))] * 2),
    ("unknown trigger gives no line", "L01_first_crate", CONFIG,
     [("nope", ctx(1, "amused"))] * 2),
    ("a single-line trigger repeats its only line", "L01_first_crate", CONFIG,
     [("solo", ctx(1, "amused"))] * 4),
    ("two-line trigger alternates once exhausted", "L01_first_crate", CONFIG,
     [("u", ctx(1, "amused"))] * 8),
    ("recent_window 0 allows immediate repeats", "L01_first_crate",
     {**CONFIG, "recent_window": 0}, [("u", ctx(1, "amused"))] * 8),
    ("mood weights outside the allowed list are ignored", "L03_x", CONFIG,
     [("t", ctx(1, "amused", {"menacing": 5.0, "annoyed": 1.0}))] * 6),
    ("mixed triggers share one call counter", "L04_mix", CONFIG,
     [("t", ctx(2, "amused", {"amused": .5, "annoyed": .2, "menacing": .3})),
      ("u", ctx(2, "amused", {"amused": .5, "annoyed": .2, "menacing": .3}))] * 5),
]


def build():
    picker_cases = []
    for name, level_id, config, calls in SCENARIOS:
        p = DialoguePicker(LINES, config, level_id)
        expect = []
        for trig, c in calls:
            r = p.say(trig, c)
            expect.append({"mood": r["mood"], "line_id": r["line"].get("id", ""),
                           "tier": r["tier"], "repeated": r["repeated"]})
        picker_cases.append({
            "name": name, "level_id": level_id, "config": config, "lines": LINES,
            "calls": [{"trigger": t, "ctx": c} for t, c in calls], "expect": expect,
        })
    rng_cases = []
    for seed in (0, 1, 12345, 4294967295, seed_from_string("L01_first_crate#0")):
        r = Rng(seed)
        rng_cases.append({"seed": seed, "first5": [r.next_u32() for _ in range(5)]})
    seed_cases = [{"text": t, "seed": seed_from_string(t)}
                  for t in ("", "a", "L01_first_crate#0", "L02_wake_the_shadow#17", "é")]
    return {"note": "Generated by reference/python/gen_dialogue_cases.py. Do not hand-edit.",
            "seed_cases": seed_cases, "rng_cases": rng_cases, "picker_cases": picker_cases}


if __name__ == "__main__":
    data = build()
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8") as f:
        json.dump(data, f, indent=1, ensure_ascii=False)
        f.write("\n")
    print(f"wrote {os.path.relpath(OUT)}: {len(data['picker_cases'])} picker cases, "
          f"{len(data['rng_cases'])} rng cases, {len(data['seed_cases'])} seed cases")
